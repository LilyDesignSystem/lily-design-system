<section class="prose">
  <h2>The short version</h2>
  <ul>
    <li>No accounts, no sign-in, no forms that send data to us.</li>
    <li>No analytics, advertising, tracking pixels or cookies.</li>
    <li>No third-party scripts, fonts or embedded media loaded from other companies.</li>
    <li>Your theme, text size and language choices stay in your own browser.</li>
  </ul>

  <h2>What we collect</h2>
  <p>
    <strong>We do not collect personal information about visitors.</strong> The website does not send any information about
    you or your visit to us.
  </p>

  <h2>What is stored on your device</h2>
  <p>
    A few preferences are kept in your browser’s storage so that your choices last. They stay on your device. See the
    <a href="/en-001/cookie-policy/">cookie policy</a> for the full list.
  </p>

  <h2>Who else can see your visit</h2>
  <p>
    A website is delivered by a hosting company, and when your browser asks for a page, the host necessarily receives
    that request, which includes your network address. That is how every website works. This site’s files are hosted on a
    public code-hosting service, and its own privacy statement describes what it keeps. We do not receive that data
    and do not use it.
  </p>
  <p>Your own internet provider, network and browser can also see which sites you visit; they are outside our control.</p>

  <h2>Examples and demonstrations</h2>
  <p>
    Example pages, including the health-care examples, use invented people and data. Anything you type into them stays on
    the page in your browser and is not sent anywhere. Please do not type real personal or health information into an
    example.
  </p>

  <h2>If you contact us</h2>
  <p>
    You can report a problem or ask a question through <a href="https://github.com/LilyDesignSystem/lily-design-system/issues">the public issue tracker</a>
    or by email. Anything you post in the issue tracker is public, and is held by the code-hosting service under its own
    terms. We use what you tell us only to answer you and to improve the project. We do not add you to a mailing list, and
    we do not share your message, except that a public issue is public.
  </p>
  <p>Security problems should be reported privately, following the <a href="https://github.com/LilyDesignSystem/lily-design-system/blob/main/SECURITY.md">security policy</a>.</p>

  <h2>Your rights</h2>
  <p>
    Because we hold no personal information about visitors, there is normally nothing to access, correct or delete. If you
    have contacted us and want your message removed, ask, and we will remove it where we are able. Data protection laws differ
    by country; wherever you live, you keep the rights those laws give you, including the right to complain to your
    local data protection authority.
  </p>

  <h2>Children</h2>
  <p>The site is not aimed at children and collects nothing from anyone, including children.</p>

  <h2>Changes</h2>
  <p>
    If this changes, for example if we ever add analytics, we will update this page first and say so on the front page. This
    policy was last reviewed on 21 November 2026.
  </p>
</section>
