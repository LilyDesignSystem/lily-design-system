#!/usr/bin/env node
// Build pipeline for @lilydesignsystem/solid-headless.
//
//   1. Generate `index.ts`, the public barrel: every component in `components/` by name, with the prop types it
//      declares (discovered, not assumed: GanttTableTD exports GanttTableTdProps), and the public pure modules.
//   2. `tsc -p tsconfig.build.json`: the JSX kept as JSX, with declarations, in dist/source. A Solid app resolves the
//      "solid" export condition to these, so its own Solid compiler builds them for the browser or the server.
//   3. Vite in library mode with @solidjs/vite-plugin: the components compiled for the browser, in dist/index.js, for
//      any other bundler. solid-js and @solidjs/web stay external (peer dependencies).
import { execFileSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

import solid from "@solidjs/vite-plugin";
import { build } from "vite";

const root = path.dirname(fileURLToPath(import.meta.url));
const componentsDir = path.join(root, "components");

/** Source files that are components — not tests, not test helpers. */
function isComponentSource(name) {
    if (!name.endsWith(".tsx")) return false;
    if (name.endsWith(".test.tsx")) return false;
    return true;
}

const files = fs.readdirSync(componentsDir).filter(isComponentSource).sort();

if (files.length === 0) {
    throw new Error(`No component sources found in ${componentsDir}.`);
}

const lines = [];
const seen = new Map();

for (const file of files) {
    const name = file.slice(0, -".tsx".length);
    const source = fs.readFileSync(path.join(componentsDir, file), "utf8");
    const types = [...source.matchAll(/^export (?:interface|type) ([A-Za-z0-9_]+)/gm)].map(
        (match) => match[1],
    );

    lines.push(`export { default as ${name} } from "./components/${name}";`);
    if (types.length > 0) {
        lines.push(`export type { ${types.join(", ")} } from "./components/${name}";`);
    }

    // A duplicated export name makes the barrel ambiguous, and bundlers
    // resolve that by dropping one side silently. Fail loudly instead.
    for (const exported of [name, ...types]) {
        if (seen.has(exported)) {
            throw new Error(
                `Duplicate export "${exported}": declared by both ` +
                    `${seen.get(exported)} and ${file}.`,
            );
        }
        seen.set(exported, file);
    }
}

fs.writeFileSync(
    path.join(root, "index.ts"),
    "// Generated by build.mjs — do not edit by hand.\n" +
        "// Barrel export of the national personal identifier components of the Lily Design System catalog.\n\n" +
        lines.join("\n") +
        "\n",
);
console.log(`generated index.ts (${files.length} components)`);

fs.rmSync(path.join(root, "dist"), { recursive: true, force: true });

execFileSync("npx", ["tsc", "-p", "tsconfig.build.json"], { cwd: root, stdio: "inherit" });

await build({
    root,
    configFile: false,
    logLevel: "warn",
    plugins: [solid()],
    build: {
        outDir: "dist",
        emptyOutDir: false,
        sourcemap: true,
        minify: false,
        lib: { entry: path.join(root, "index.ts"), formats: ["es"], fileName: () => "index.js" },
        rolldownOptions: {
            external: (id) => /^(solid-js|@solidjs\/web)(\/|$)/.test(id),
        },
    },
});

// `files` ships only dist/: an empty or missing artifact would publish a package that installs and exports nothing.
for (const artifact of [
    "index.js",
    "source/index.js",
    "source/index.d.ts",
    "source/components/UnitedKingdomNationalHealthServiceNumberInput.jsx",
]) {
    const file = path.join(root, "dist", artifact);
    if (!fs.existsSync(file) || fs.statSync(file).size === 0) {
        throw new Error(`expected a non-empty dist/${artifact} after build.`);
    }
}
console.log("build ok");
