// PortugalNumeroDeIdentificacaoFiscalView component
//
// A headless display component for showing Portugal's
// Número de Identificação Fiscal (NIF) in a read-only format.
//
// Props:
//   class — string, optional. CSS class name.
//   label — string, optional. Hidden text naming the value. Leave it out when a visible caption, such as a dt or a SummaryListItem term, already names it.
//   value — string, default "". The identifier string to display.
//   ...restProps — additional HTML attributes spread onto the <span>.
//
// Syntax:
//   <PortugalNumeroDeIdentificacaoFiscalView label="Tax Identification Number" value={value} />
//
// Accessibility:
//   - A visible caption names the value, or label renders as hidden text; a plain span cannot take aria-label.
//
// References:
//   - https://en.wikipedia.org/wiki/Personal_identification_number_(Portugal)

import { merge, omit } from "solid-js";
export interface PortugalNumeroDeIdentificacaoFiscalViewProps {
    class?: string;
    /** Accessible label for screen readers */
    label?: string;
    /** The identifier to display */
    value?: string;
    [key: string]: unknown;
}

export default function PortugalNumeroDeIdentificacaoFiscalView(
    props: PortugalNumeroDeIdentificacaoFiscalViewProps,
) {
    const p = merge({ class: "" as const, value: "" as const }, props);
    const restProps = omit(p, "class", "label", "value");
    return (
        <span
            class={`portugal-numero-de-identificacao-fiscal-view ${p.class}`}
            {...restProps}
        >
            {p.label ? <span class="screen-reader-span">{`${p.label} `}</span> : null}
            {p.value}
        </span>
    );
}
