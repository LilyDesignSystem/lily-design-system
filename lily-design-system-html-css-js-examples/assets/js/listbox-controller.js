/**
 * ListboxController — shared WAI-ARIA APG listbox keyboard behaviour.
 *
 * `listbox.html`'s own behaviour script has always been an empty stub
 * (`// Interactive behavior initialization`, no code) — there was never a
 * working keyboard implementation to extend here, unlike the other seven
 * framework catalogs' `Listbox` components. Six `*-picker` custom elements
 * in `lily-design-system-html-helpers` each hand-rolled an near-identical
 * ~150-line copy of this same logic instead. This module is that logic,
 * extracted once, real and reusable, so the six no longer duplicate it.
 *
 * A framework-free, dependency-free plain ES module (this catalog has no
 * TypeScript/bundler pipeline for its runtime components — only Storybook
 * stories are `.ts`), matching `theme-picker.ts`'s own class-based style.
 *
 * Unlike Blazor's port, this catalog CAN query the live DOM synchronously,
 * so — like Svelte/Vue/React — options are read straight off the rendered
 * `[role="option"]` children of `root` rather than through index-mapping
 * callbacks. `ListboxController` owns only the cursor mechanics (arrow
 * movement, Home/End, typeahead, PageUp/PageDown) and calls back into the
 * consumer for what "activate" / "escape" / "tab out" actually do — the
 * same division of responsibility the other catalogs' Listbox components
 * use.
 *
 * Every keyboard decision is made by the shared listbox machine
 * (shared/listbox-machine.ts and the two modules it imports), inlined
 * below by bin/sync-shared-modules so this stays one dependency-free file
 * that also runs as a classic script once `export` is dropped.
 *
 * @example
 *   const controller = new ListboxController({
 *     root: listEl,
 *     clamp: true,
 *     typeahead: true,
 *     getOptionLabel: (option) => option.textContent ?? "",
 *     onActiveIndexChange: (index) => { ...update aria-activedescendant/data-active... },
 *     onActivate: (index) => { ...choose(index)... },
 *     onEscape: () => closeList(),
 *     onTabOut: () => { buttonEl.focus(); closeList(false); },
 *   });
 *   controller.setActiveIndex(0); // on open
 *   controller.destroy(); // on disconnect
 */

/* BEGIN shared/search-text.ts (generated by bin/sync-shared-modules; do not edit) */
/**
 * Search matching shared by the data grid, kanban board, Gantt chart and calendar: pure, so it is unit-tested without a browser.
 *
 * A query is split on whitespace into terms; every term must appear (AND), in any order, ignoring case and diacritics
 * ("cafe" finds "Café"). An empty query matches everything.
 */

/** Lower-case and strip combining marks, so matching ignores case and diacritics. */
function foldText(text) {
    return text
        .normalize("NFD")
        .replace(/\p{M}+/gu, "")
        .toLowerCase();
}

/** The terms of a query, folded; empty when the query is blank. */
function searchTerms(query) {
    return foldText(query).split(/\s+/).filter(Boolean);
}

/** True when every term of `query` appears in `text`. */
function matchesSearch(text, query) {
    const terms = searchTerms(query);
    if (terms.length === 0) return true;
    const folded = foldText(text);
    return terms.every((term) => folded.includes(term));
}

/**
 * `text` cut into runs, marking the parts any term matches (for `<mark>`). Folding can change a string's length (a precomposed "é"
 * is one character, its folded form too, but a ligature may not be), so matching works on a per-character fold and falls back to
 * one unmarked segment if the two ever disagree.
 */
function highlightSegments(text, query) {
    const terms = searchTerms(query);
    if (terms.length === 0 || text === "") return [{ text, match: false }];
    const chars = Array.from(text);
    const folded = chars.map((c) => foldText(c));
    if (folded.some((f) => f.length !== 1)) return [{ text, match: false }];
    const flat = folded.join("");
    const marked = new Array(chars.length).fill(false);
    for (const term of terms) {
        for (let at = flat.indexOf(term); at !== -1; at = flat.indexOf(term, at + 1)) {
            for (let i = at; i < at + term.length; i++) marked[i] = true;
        }
    }
    const out = [];
    chars.forEach((c, i) => {
        const last = out[out.length - 1];
        if (last && last.match === marked[i]) last.text += c;
        else out.push({ text: c, match: marked[i] });
    });
    return out;
}
